    # (key, display_label, arrow, lamp_slot, filename) -- one entry per unique
    # meter design. `key` is only a lookup name for meter_frames/CELLS below;
    # `display_label` is the text actually baked onto the dial, which is why
    # DiskRead ("R") and the new AudioR meter (key "AudioR", also displayed
    # as "R") can coexist. CPU/MEM look identical in both compact and full,
    # so their files are reused by both layout.cfg sections instead of
    # duplicated. SND is compact-only (mono volume); AudioL/AudioR are
    # full-only (stereo volume) and share SND's design apart from the label.
    METERS = [
        ("CPU", "CPU", "", False, "vintage_cpu.png"),
        ("MEM", "MEM", "", False, "vintage_mem.png"),
        ("DSK", "DSK", "", True, "vintage_dsk.png"),
        ("NET", "NET", "", True, "vintage_net.png"),
        ("SND", "SND", "", False, "vintage_snd.png"),
        ("SWP", "SWP", "", False, "vintage_swp.png"),
        ("R", "R", "down", True, "vintage_r.png"),
        ("W", "W", "up", True, "vintage_w.png"),
        ("IN", "IN", "down", True, "vintage_in.png"),
        ("OUT", "OUT", "up", True, "vintage_out.png"),
        ("AudioL", "L", "", False, "vintage_sndl.png"),
        ("AudioR", "R", "", False, "vintage_sndr.png"),
    ]
    meter_frames = {}
    for key, display, arrow, lamp_slot, filename in METERS:
        meter_frames[key] = build_meter_strip(display, arrow, lamp_slot, filename)

    build_lamp_strip("vintage_lamp.png")

    COMPACT_CELLS = [("CPU", ""), ("MEM", ""), ("DSK", ""), ("NET", ""), ("SND", "")]
    FULL_CELLS = [("CPU", ""), ("MEM", ""), ("SWP", ""), ("R", "down"), ("W", "up"),
                  ("IN", "down"), ("OUT", "up"), ("AudioL", ""), ("AudioR", "")]
    COMPACT_LAMP_SLOTS = {2, 3}          # DSK, NET
    FULL_LAMP_SLOTS = {3, 4, 5, 6}       # R, W, IN, OUT

    build_background(COMPACT_CELLS, "vintage_compact_bg.png")
    build_background(FULL_CELLS, "vintage_full_bg.png")

    # layout.cfg coordinates -- printed here (not hand-derived) so the values
    # written into assets/vintage/layout.cfg can't drift from what these
    # assets actually assume.
    print("\n-- layout.cfg positions (design px) --")
    print("meter strip frame size: %dx%d, Frames=%d" %
          (int(math.ceil(CASE_W)), int(math.ceil(CASE_H)), NEEDLE_FRAMES))
    print("lamp strip:   File=vintage_lamp.png Frames=2, frame size %dx%d" %
          (LAMP_FRAME_D, LAMP_FRAME_D))
    for mode, cells, lamp_slots in (("compact", COMPACT_CELLS, COMPACT_LAMP_SLOTS),
                                     ("full", FULL_CELLS, FULL_LAMP_SLOTS)):
        for i, (name, _arrow) in enumerate(cells):
            lx, ly = lamp_xy(i) if i in lamp_slots else (None, None)
            print("  %-8s[%d] %-4s X=%d Y=0%s" % (
                mode, i, name, case_x(i),
                "  lamp X=%d Y=%d" % (lx, ly) if lx is not None else ""))

    # Full-scene review previews (needle values + lamp on/off are arbitrary
    # demo values, not meaningful data).
    compact_lamp_demo = {2: False, 3: True}          # DSK=off, NET=on
    full_lamp_demo = {3: False, 4: True, 5: False, 6: True}  # R=off,W=on,IN=off,OUT=on
    build_scene_preview(COMPACT_CELLS, COMPACT_LAMP_SLOTS, meter_frames,
                         [0.12, 0.38, 0.62, 0.85, 0.5], compact_lamp_demo, "preview_compact.png")
    build_scene_preview(FULL_CELLS, FULL_LAMP_SLOTS, meter_frames,
                         [0.15, 0.4, 0.55, 0.3, 0.7, 0.2, 0.85, 0.3, 0.6], full_lamp_demo, "preview_full.png")
